"""Turn the output of ``scripts/calibrate_stage0.py`` into figures and a Results section (#14).

Everything written into the docs comes from the run's own files (the JSON report and the CSVs), so no
number is typed by hand. The section sits between two marker comments in ``docs/stage_calibration.md``
and is replaced, not duplicated, when this is run again.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import pandas as pd

START = "<!-- RESULTS:START (generated by scripts/write_calibration_results.py - do not edit by hand) -->"
END = "<!-- RESULTS:END -->"


def _f(x, nd=3):
    try:
        return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return str(x)


def _table(df: pd.DataFrame, cols: list[tuple[str, str, int]]) -> str:
    """Markdown table. ``cols`` is (column, header, decimals); decimals -1 means text."""
    head = "| " + " | ".join(h for _, h, _ in cols) + " |"
    rule = "|" + "|".join("---" for _ in cols) + "|"
    rows = []
    for _, r in df.iterrows():
        cells = [str(r[c]) if nd < 0 else _f(r[c], nd) for c, _, nd in cols]
        rows.append("| " + " | ".join(cells) + " |")
    return "\n".join([head, rule, *rows])


def make_figures(report_dir: Path) -> list[Path]:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    report = json.loads((report_dir / "stage_calibration_report.json").read_text())
    curve = pd.read_csv(report_dir / "stage0_calibration_curve.csv")
    by_date = pd.read_csv(report_dir / "hand_inundation_by_date.csv")
    paths = []

    fig, ax = plt.subplots(figsize=(8, 4.5))
    for col in [c for c in curve.columns if c.startswith("iou_")]:
        ax.plot(curve["stage0_m"], curve[col], label=f"IoU, fit date {col[4:]}")
    if "mean_iou" in curve and len([c for c in curve.columns if c.startswith("iou_")]) > 1:
        ax.plot(curve["stage0_m"], curve["mean_iou"], "k--", label="mean IoU")
    lo, hi = report["stage0_range_m"]
    ax.axvspan(lo, hi, alpha=0.15, color="tab:green", label=f"near-optimal range {lo:.2f}-{hi:.2f} m")
    ax.axvline(report["stage0_m"], color="tab:green", lw=1.5, label=f"stage0 = {report['stage0_m']:.2f} m")
    ax.set_xlabel("candidate stage0 (m, gauge units converted to metres)")
    ax.set_ylabel("IoU of {HAND <= stage - stage0} vs reference")
    ax.set_title("Calibrating stage0 against the independent reference")
    ax.grid(alpha=0.3)
    ax.legend(fontsize=8)
    fig.tight_layout()
    p = report_dir / "stage0_calibration_curve.png"
    fig.savefig(p, dpi=160)
    plt.close(fig)
    paths.append(p)

    ok = by_date[by_date["status"].isin(["ok", "below_hand0"])].copy()
    if len(ok):
        fig, ax = plt.subplots(figsize=(8, 4.5))
        dates = pd.to_datetime(ok["acquisition_date"])
        ax.bar(dates, 100 * ok["wet_fraction"], width=5, color="tab:blue", alpha=0.8)
        ax.set_ylabel("area predicted wet (% of valid HAND pixels)")
        ax.set_xlabel("NISAR acquisition date")
        ax2 = ax.twinx()
        ax2.plot(dates, ok["stage_m"], "o-", color="tab:red")
        ax2.set_ylabel("Manaus daily mean stage (m)", color="tab:red")
        ax.set_title("HAND-predicted inundation per NISAR date")
        ax.grid(alpha=0.3)
        fig.autofmt_xdate()
        fig.tight_layout()
        p = report_dir / "hand_inundation_by_date.png"
        fig.savefig(p, dpi=160)
        plt.close(fig)
        paths.append(p)
    return paths


def render_results(
    report_dir: str | Path,
    doc_path: str | Path,
    reference_notes: str = "",
    reference_summary: dict | None = None,
) -> str:
    """Build the Results markdown and write it into ``doc_path`` between the markers."""
    report_dir, doc_path = Path(report_dir), Path(doc_path)
    report = json.loads((report_dir / "stage_calibration_report.json").read_text())
    by_date = pd.read_csv(report_dir / "hand_inundation_by_date.csv")
    fit = pd.DataFrame(report["calibration_dates"])
    check = pd.DataFrame(report.get("out_of_sample_checks") or [])
    lo, hi = report["stage0_range_m"]

    lines = ["## Results (real data)", ""]
    lines.append(f"Generated {report['created_utc']} by `scripts/calibrate_stage0.py` "
                 f"(HAND: `{Path(report['hand']).name}`).")
    if reference_notes:
        lines += ["", "**Independent reference.** " + reference_notes.strip()]

    lines += ["", "### stage0", ""]
    if report["plateau_reaches_search_edge"]:
        lines.append("> **WARNING: the near-optimal range reaches the edge of the search grid. The reference does "
                     "not bound `stage0` (or the search range is too narrow). Do not use the value below.**")
        lines.append("")
    lines.append(f"- `stage0` = **{report['stage0_m']:.2f} m** (gauge stage at which the floodplain waterline is at HAND = 0)")
    lines.append(f"- Near-optimal range (within 0.005 IoU of the best): **{lo:.2f} to {hi:.2f} m**, "
                 f"width {hi - lo:.2f} m. This is the calibration uncertainty to quote.")
    lines.append(f"- Mean IoU on the fit date(s): **{report['mean_iou']:.3f}**")
    lines += ["", "![stage0 calibration curve](evidence/stage0_calibration_curve.png)"]

    cols = [("date", "Date", -1), ("stage_m", "Stage (m)", 2), ("water_height_m", "h = stage - stage0 (m)", 2),
            ("iou", "IoU", 3), ("precision", "Precision", 3), ("recall", "Recall", 3), ("f1", "F1", 3)]
    lines += ["", "### Agreement on the fit date(s)", "", _table(fit, cols)]
    if len(check):
        lines += ["", "### Agreement on held-out dates (not used to fit `stage0`)", "", _table(check, cols)]
    else:
        lines += ["", "No held-out date was scored; the agreement above is in-sample only."]

    reading = (
        "**Reading these numbers.** The reference sees open water only. HAND also predicts water under "
        "canopy (flooded forest) that the reference cannot see, so *precision* is expected to be lower than "
        "*recall*, most of all at high water. Recall (how much of the reference water HAND recovers) is the "
        "cleaner figure. IoU mixes in the flooded-forest area the reference is blind to."
    )
    lines += ["", reading]

    if reference_summary:
        rs = pd.DataFrame(
            [{"date": d, "tiles": s.get("n_tiles"), "known": 100 * s.get("known_fraction", float("nan")),
              "water": 100 * s.get("water_fraction_of_known", float("nan"))}
             for d, s in sorted(reference_summary.items())]
        )
        lines += ["", "### Reference coverage", "",
                  _table(rs, [("date", "Date", -1), ("tiles", "Tiles", -1),
                              ("known", "Area with a valid reference (%)", 1),
                              ("water", "Water share of valid area (%)", 1)])]
        unmapped = {d: s["unmapped_codes"] for d, s in reference_summary.items() if s.get("unmapped_codes")}
        if unmapped:
            parts = [
                f"{d}: " + ", ".join(f"code {c} ({int(n):,} px)" for c, n in sorted(codes.items(), key=lambda kv: int(kv[0])))
                for d, codes in sorted(unmapped.items())
            ]
            lines += ["", "Class codes that were not listed as water, not-water or unknown were treated as unknown "
                      "(never as water): " + "; ".join(parts) + "."]

    gcols = [("acquisition_date", "Date", -1), ("stage_m", "Stage (m)", 2), ("water_height_m", "h (m)", 2),
             ("wet_fraction", "Predicted wet fraction", 3), ("status", "Status", -1)]
    masks_note = (
        "Per-date masks (1 = wet, 0 = dry, 255 = no HAND value) are written as GeoTIFFs and kept out of git "
        "(`data/reference/` is ignored); they are regenerated by `scripts/calibrate_stage0.py`. Raw numbers: "
        "`docs/evidence/stage_calibration_report.json`, `stage0_calibration_curve.csv`, "
        "`hand_inundation_by_date.csv`."
    )
    lines += [
        "", "### Per-date inundation prediction", "", _table(by_date, gcols),
        "", "![predicted inundation per date](evidence/hand_inundation_by_date.png)",
        "", masks_note,
    ]

    section = "\n".join(lines) + "\n"
    block = f"{START}\n{section}{END}\n"
    text = doc_path.read_text() if doc_path.exists() else ""
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        text = head + block + tail.lstrip("\n")
    else:
        text = text.rstrip("\n") + "\n\n" + block
    doc_path.write_text(text)
    return section
